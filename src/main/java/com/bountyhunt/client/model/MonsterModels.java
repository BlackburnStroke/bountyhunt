package com.bountyhunt.client.model;

import com.bountyhunt.BountyHuntMod;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.fabricmc.fabric.api.client.rendering.v1.EntityModelLayerRegistry;
import net.minecraft.client.model.Dilation;
import net.minecraft.client.model.ModelData;
import net.minecraft.client.model.ModelPartBuilder;
import net.minecraft.client.model.ModelPartData;
import net.minecraft.client.model.ModelTransform;
import net.minecraft.client.model.TexturedModelData;
import net.minecraft.client.render.entity.model.BipedEntityModel;
import net.minecraft.client.render.entity.model.EntityModelLayer;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.HashMap;
import java.util.Map;

/**
 * Builds the per-tier bounty monster models: the vanilla biped skeleton plus the extra cuboids listed in
 * assets/bountyhunt/monster_models/*.json (generated by tools/gen_bounty_*.py).
 * The zombie uses the classic biped limbs, the skeleton uses the slim 2px limbs.
 */
public final class MonsterModels {
	public static final EntityModelLayer[] ZOMBIE_LAYERS = new EntityModelLayer[4];
	public static final EntityModelLayer[] SKELETON_LAYERS = new EntityModelLayer[4];

	static {
		for (int i = 0; i < ZOMBIE_LAYERS.length; i++) {
			ZOMBIE_LAYERS[i] = new EntityModelLayer(BountyHuntMod.id("bounty_zombie"), "tier_" + i);
			SKELETON_LAYERS[i] = new EntityModelLayer(BountyHuntMod.id("bounty_skeleton"), "tier_" + i);
		}
	}

	private static final Map<String, JsonObject> data = new HashMap<>();

	private MonsterModels() {
	}

	public static void registerLayers() {
		for (int i = 0; i < ZOMBIE_LAYERS.length; i++) {
			final int tier = i;
			EntityModelLayerRegistry.registerModelLayer(ZOMBIE_LAYERS[i], () -> make(tier, "bounty_zombie.json", false));
			EntityModelLayerRegistry.registerModelLayer(SKELETON_LAYERS[i], () -> make(tier, "bounty_skeleton.json", true));
		}
	}

	private static synchronized JsonObject data(String file) {
		if (!data.containsKey(file)) {
			try (InputStream in = MonsterModels.class.getResourceAsStream("/assets/bountyhunt/monster_models/" + file)) {
				if (in == null) {
					throw new IllegalStateException(file + " is missing");
				}
				data.put(file, JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject());
			} catch (IOException e) {
				throw new IllegalStateException(e);
			}
		}
		return data.get(file);
	}

	private static float f(JsonArray a, int i) {
		return a.get(i).getAsFloat();
	}

	private static void addExtras(ModelPartData root, String file, int tier) {
		JsonObject json = data(file);
		JsonArray parts = json.getAsJsonArray("tiers").get(tier).getAsJsonArray();
		for (JsonElement element : parts) {
			JsonObject o = element.getAsJsonObject();
			ModelPartData parent = root;
			for (String segment : o.get("p").getAsString().split("/")) {
				parent = parent.getChild(segment);
			}
			JsonArray uv = o.getAsJsonArray("uv");
			JsonArray b = o.getAsJsonArray("b");
			JsonArray pivot = o.getAsJsonArray("o");
			JsonArray rot = o.getAsJsonArray("r");
			parent.addChild(o.get("n").getAsString(),
					ModelPartBuilder.create().uv(uv.get(0).getAsInt(), uv.get(1).getAsInt())
							.cuboid(f(b, 0), f(b, 1), f(b, 2), f(b, 3), f(b, 4), f(b, 5)),
					ModelTransform.of(f(pivot, 0), f(pivot, 1), f(pivot, 2), f(rot, 0), f(rot, 1), f(rot, 2)));
		}
	}

	/** Builds one tier model: "file" is the monster model json; slim swaps in the skeleton's 2px limbs. */
	private static TexturedModelData make(int tier, String file, boolean slim) {
		ModelData modelData = BipedEntityModel.getModelData(Dilation.NONE, 0.0f);
		ModelPartData root = modelData.getRoot();
		if (slim) {
			// vanilla skeleton limbs: 2px arms and legs, shared textures for the mirrored pairs
			root.addChild("right_arm", ModelPartBuilder.create().uv(40, 16)
					.cuboid(-2.0f, -2.0f, -2.0f, 2, 12, 2), ModelTransform.pivot(-5.0f, 2.0f, 0.0f));
			root.addChild("left_arm", ModelPartBuilder.create().uv(40, 16).mirrored()
					.cuboid(-1.0f, -2.0f, -2.0f, 2, 12, 2), ModelTransform.pivot(5.0f, 2.0f, 0.0f));
			root.addChild("right_leg", ModelPartBuilder.create().uv(0, 16)
					.cuboid(-1.0f, 0.0f, -1.0f, 2, 12, 2), ModelTransform.pivot(-2.0f, 12.0f, 0.0f));
			root.addChild("left_leg", ModelPartBuilder.create().uv(0, 16).mirrored()
					.cuboid(-1.0f, 0.0f, -1.0f, 2, 12, 2), ModelTransform.pivot(2.0f, 12.0f, 0.0f));
		}
		addExtras(root, file, tier);
		JsonArray size = data(file).getAsJsonArray("texture");
		return TexturedModelData.of(modelData, size.get(0).getAsInt(), size.get(1).getAsInt());
	}
}
